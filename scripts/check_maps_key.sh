#!/usr/bin/env bash
# ============================================================================
# check_maps_key.sh — حارسُ مفتاح خرائط جوجل للخطّين (iOS وأندرويد).
# ----------------------------------------------------------------------------
# منذ 2834af3 خرج المفتاحُ من المستودع (كان مكتوبًا نصًّا في AppDelegate.swift
# وAndroidManifest.xml، والمستودعُ منشور) وصار يُقرأ من MAPS_API_KEY وقتَ البناء
# وحدَه. ولم يُضف المتغيّرُ إلى Codemagic بعد — فكان البناءُ التالي سيخرج
# **أخضرَ بلا خريطة**: `Env.hasMaps` كاذبة، فيرى المندوبُ لوحةَ «الخريطة غير
# متاحة» مكان الخريطة، والسجلُّ فيه سطرٌ أصفرُ لا يقرؤه أحد.
#
# ⛔ فالحارسُ يُوقف البناء كما يُوقفه حارسُ Firebase (check_firebase_android.sh)
#    — للسبب نفسِه: الصمتُ هو العطل، فلا يُعالَج بصوتٍ خافت. ويقع **أوّلَ**
#    الخطّ لا قبل البناء مباشرة: فشلٌ بعد التوقيع والـpods يُهدر نصفَ ساعة.
#
# المتغيّر: MAPS_API_KEY في مجموعة «platform_shared» (مفتاحُ المنصّة — تطبيقُ
#   المندوب واحدٌ لكلّ المطاعم، لا مفتاحَ مؤسّسة).
# ولبناءٍ بلا خريطةٍ عمدًا (إصلاحٌ عاجلٌ مثلًا):  ALLOW_NO_MAPS=1
#   — والتطبيقُ حينها لا ينهار: الحارسُ في Dart يضع لوحةً بديلة ويُبقي زرَّ
#     «افتح في خرائط جوجل» عاملًا.
# ============================================================================
set -euo pipefail

KEY="${MAPS_API_KEY:-}"
# مسافةٌ أو سطرٌ زائدٌ عند اللصق في واجهة Codemagic يجعل المفتاحَ «موجودًا»
# ومرفوضًا عند جوجل — خريطةٌ رماديّةٌ بلا خطأ. فيُقاس بعد التشذيب.
TRIMMED="$(printf '%s' "$KEY" | tr -d '[:space:]')"

if [ -z "$TRIMMED" ]; then
  if [ "${ALLOW_NO_MAPS:-}" = "1" ]; then
    echo "⚠ بناءٌ بلا خريطة بطلبٍ صريح (ALLOW_NO_MAPS=1): يرى المندوبُ لوحةَ «الخريطة غير متاحة»."
    exit 0
  fi
  echo "✗ ينقص MAPS_API_KEY — لن تُعرض خريطةٌ في تطبيق المندوب." >&2
  echo "  أضفه (مفتاح Google Maps للمنصّة) إلى مجموعة المتغيّرات «platform_shared»" >&2
  echo "  في تطبيق moaatmat-driver على Codemagic، ثمّ أعد البناء." >&2
  echo "  ولبناءٍ بلا خريطةٍ عمدًا: ALLOW_NO_MAPS=1" >&2
  exit 1
fi

if [ "$TRIMMED" != "$KEY" ]; then
  echo "✗ في MAPS_API_KEY مسافةٌ أو سطرٌ زائد — صحّحه في Codemagic (جوجل يرفضه فتخرج الخريطةُ رماديّة)." >&2
  exit 1
fi

# مفاتيحُ Google API شكلُها ثابت: AIza + ٣٥ محرفًا. شكلٌ آخر = لصقُ شيءٍ آخر
# (معرّفُ مشروعٍ أو سرٌّ آخر). تحذيرٌ لا إيقاف: الشكلُ عُرفٌ لا عقدٌ منشور.
if ! printf '%s' "$KEY" | grep -Eq '^AIza[0-9A-Za-z_-]{35}$'; then
  echo "⚠ MAPS_API_KEY لا يشبه مفتاحَ Google API (AIza…، ٣٩ محرفًا) — تحقّق أنّه المفتاحُ الصحيح."
fi

# يُطبع الطول لا المفتاح: سجلّات Codemagic تُقرأ ويُشارَك رابطها.
echo "✅ مفتاح الخرائط حاضر (${#KEY} حرفًا)"
